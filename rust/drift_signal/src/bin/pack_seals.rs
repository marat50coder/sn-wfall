// ============================================================
//  pack_seals — dev-time encoder for sealed_data.rs
// ============================================================
//  Reads the plaintext slot table out of `pack_seeds.rs`
//  (which lives next to this file and is .gitignored because
//  it contains the raw endpoint / dev key / project id), runs
//  every entry through the layered codec, and writes the
//  result into src/sealed_data.rs.
//
//  Workflow:
//
//    cd rust/prism_core
//    cp src/bin/pack_seeds.example.rs src/bin/pack_seeds.rs
//    # edit the plaintexts
//    cargo run --release --bin pack_seals
//
//  The committed src/sealed_data.rs is pure ciphertext — no
//  plaintext ever lands in git.
// ============================================================

use std::fs;
use std::path::PathBuf;

#[path = "../ciphers.rs"]
mod ciphers;

#[path = "../../seeds/entries.rs"]
mod seeds;

fn main() {
    let out = render(seeds::seed_entries());
    let target = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/sealed_data.rs");
    fs::write(&target, out).expect("write sealed_data.rs");
    eprintln!("packed → {}", target.display());
}

fn render(rows: &[(&'static str, u32, &'static str)]) -> String {
    let mut salt_a: u16 = 0x7B4D;
    let mut salt_b: u16 = 0xA291;

    let mut body = String::new();
    body.push_str(HEADER);

    // Slot constants.
    for (name, id, _) in rows {
        body.push_str(&format!("pub(crate) const SLOT_{name}: u32 = 0x{id:08X};\n"));
    }
    body.push('\n');

    // Table.
    body.push_str("pub(crate) struct Slot {\n    pub cipher: &'static [u8],\n    pub salt_a: u16,\n    pub salt_b: u16,\n}\n\n");
    body.push_str("pub(crate) static TABLE: &[(u32, Slot)] = &[\n");

    for (name, _id, plain) in rows {
        salt_a = salt_a.wrapping_mul(0x9E37).wrapping_add(0xB1C3);
        salt_b = salt_b.wrapping_mul(0xC2B2).wrapping_add(0x1965);
        let cipher = ciphers::transcode(plain.as_bytes(), salt_a, salt_b);
        let bytes = format_bytes(&cipher);
        body.push_str(&format!(
            "    (SLOT_{name}, Slot {{ cipher: &{bytes}, salt_a: 0x{salt_a:04X}, salt_b: 0x{salt_b:04X} }}),\n"
        ));
    }
    body.push_str("];\n\n");
    body.push_str(LOOKUP);
    body
}

fn format_bytes(b: &[u8]) -> String {
    let mut s = String::from("[");
    for (i, byte) in b.iter().enumerate() {
        if i % 12 == 0 { s.push_str("\n        "); }
        s.push_str(&format!("0x{byte:02X}, "));
    }
    s.push_str("\n    ]");
    s
}

const HEADER: &str = "// ============================================================\n// AUTO-GENERATED by src/bin/pack_seals.rs. Do not hand-edit.\n// ============================================================\n\n";

const LOOKUP: &str = "#[inline(never)]\npub(crate) fn lookup(id: u32) -> Option<&'static Slot> {\n    for (sid, slot) in TABLE.iter() {\n        if *sid == id { return Some(slot); }\n    }\n    None\n}\n";
